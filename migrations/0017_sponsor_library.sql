-- A sponsor library for all events. The name, link, logo and background colour of a sponsor move
-- to sponsor_library, so an admin adds a sponsor once and uses it at many events. The sponsors
-- table keeps one row per sponsor at an event, with its position and whether it is shown. Its ids
-- stay, so the game server, the logo addresses and the admin pages see the same ids as before.
-- migrations/down/0017_sponsor_library.sql turns this back.
CREATE TABLE sponsor_library (
    -- By default, so the rows copied below keep the ids of the sponsors they come from.
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 60 AND name = btrim(name)),
    link text CHECK (link IS NULL OR (length(link) <= 500 AND link ~ '^https?://')),
    -- The uploaded logo, written again without metadata. Only PNG, JPEG and WebP are stored. SVG can hold scripts.
    logo bytea NOT NULL CHECK (octet_length(logo) BETWEEN 1 AND 1048576),
    logo_type text NOT NULL CHECK (logo_type IN ('image/png', 'image/jpeg', 'image/webp')),
    logo_width integer NOT NULL CHECK (logo_width BETWEEN 1 AND 2000),
    logo_height integer NOT NULL CHECK (logo_height BETWEEN 1 AND 2000),
    logo_hash text NOT NULL GENERATED ALWAYS AS (encode(sha256(logo), 'hex')) STORED,
    -- The colour of the tile behind the logo, and of transparent parts in the game. Null keeps them transparent.
    game_background text CHECK (game_background IS NULL OR game_background ~ '^#[0-9a-f]{6}$'),
    -- A BMP 32 pixels high and at most 160 wide, with alpha. 24-bit ones from before are made again by the site.
    game_logo bytea NOT NULL CHECK (octet_length(game_logo) BETWEEN 54 AND 20602),
    game_logo_hash text NOT NULL GENERATED ALWAYS AS (encode(sha256(game_logo), 'hex')) STORED,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

